namespace Lab07_AsyncThreads;

internal static class Program
{
    /// <summary>
    /// Головна точка входу для додатку.
    /// Атрибут [STAThread] вказує, що потік інтерфейсу користувача (UI Thread)
    /// використовує апартаментну модель Single-Threaded Apartment (STA),
    /// яка є обов'язковою для коректної роботи компонентів Windows Forms,
    /// буфера обміну (Clipboard) та OLE/COM діалогів.
    /// </summary>
    [STAThread]
    static void Main()
    {
        // Ініціалізація візуальних стилів, подвійної буферизації та DPI
        ApplicationConfiguration.Initialize();

        // Запуск головного вікна асинхронного обчислювального хабу
        Application.Run(new MainForm());
    }
}
