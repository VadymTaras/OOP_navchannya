#include <iostream>

using namespace std;

int main()
{
    int n;
    cout << "Введіть n: ";
    if (!(cin >> n) || n < 1) {
        cerr << "Помилка: n має бути натуральним числом (n >= 1)." << endl;
        return 1;
    }

    int sum = 0;

    // Цикл із нестрогою умовою i <= n забезпечує включення граничного значення n
    for (int i = 1; i <= n; i++)
    {
        sum += i;
        // Оператор протоколювання стану виконання (Trace / Debug Log)
        cout << "i = " << i << ", sum = " << sum << endl;
    }

    cout << "Result = " << sum << endl;
    return 0;
}
